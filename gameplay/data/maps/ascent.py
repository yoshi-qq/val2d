def m(x0: float, top: float, x1: float, bottom: float) -> tuple[float, float, float, float]:
    """Metres measured from the north-west corner (top down) to map coordinates (y up)."""
    return x0, HEIGHT - bottom, x1, HEIGHT - top


def ref(x0: float, y0: float, x1: float, y1: float) -> tuple[float, float, float, float]:
    """Reference-map pixels to map coordinates."""
    return m((x0 - REF_X0) * M_PER_PX, (y0 - REF_Y0) * M_PER_PX, (x1 - REF_X0) * M_PER_PX, (y1 - REF_Y0) * M_PER_PX)


def ref_at(x: float, y: float) -> list[float]:
    x0, y0, _, _ = ref(x, y, x, y)
    return [x0, y0]


def merged(char: str, grid=GRID) -> list[tuple[int, int, int, int]]:
    """Grid cells of one kind merged into rectangles (x0, top, x1, bottom in metres)."""
    cells = {(x, y) for y, row in enumerate(grid) for x, c in enumerate(row) if c == char}
    out = []
    while cells:
        x, y = min(cells, key=lambda cell: (cell[1], cell[0]))
        right = x + 1
        while (right, y) in cells:
            right += 1
        bottom = y + 1
        while all((col, bottom) in cells for col in range(x, right)):
            bottom += 1
        cells.difference_update((col, row) for col in range(x, right) for row in range(y, bottom))
        out.append((x, y, right, bottom))
    return out


